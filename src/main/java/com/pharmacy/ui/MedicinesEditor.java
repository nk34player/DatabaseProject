    private void saveBtn() {
        Medicine curMedicine = medicines.get(currentIndex);
        if (curMedicine != null) {
            curMedicine.setMedicineName(jTextField1.getText().trim());
            curMedicine.setCategoryId(CategoriesDB.getCategoryIdByName((String) jComboBox1.getSelectedItem()));
            curMedicine.setCompanyName((String) jComboBox2.getSelectedItem());

            String qtyText = jTextField3.getText();
            String priceText = jTextField2.getText();

            if (!isValidInteger(qtyText)) {
                JOptionPane.showMessageDialog(this, "Stock quantity must be a whole number.");
                return;
            }

            if (!isValidDouble(priceText)) {
                JOptionPane.showMessageDialog(this, "Unit price must be a valid decimal number.");
                return;
            }

            curMedicine.setUnitPrice(Double.parseDouble(jTextField2.getText().trim()));
            curMedicine.setStockQuantity(Integer.parseInt(jTextField3.getText().trim()));

            MedicinesDB.updateMedicine(curMedicine);

            currentEdit = false;
            editFields(currentEdit);
            initialRun();
        }
    }

    private void updateButtons() {
        jButton7.setEnabled(currentIndex > 0);
        jButton6.setEnabled(currentIndex < medicines.size() - 1);
    }

    private void previousUser() {
        if (currentIndex > 0) {
            currentIndex--;
            currentEdit = false;
            editFields(currentEdit);
            displayMedicine(currentIndex);
        }
        updateButtons();
    }

    private void nextUser() {
        if (currentIndex < medicines.size() - 1) {
            currentIndex++;
            currentEdit = false;
            editFields(currentEdit);
            displayMedicine(currentIndex);
        }
        updateButtons();
    }

