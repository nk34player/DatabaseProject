    private void saveBtn() {
        SuppliersDB.Supplier currentSupplier = suppliers.get(currentIndex);
        if (currentSupplier != null) {
            if (validateFields()) {
                currentSupplier.setSupplierName(jTextField1.getText());
                currentSupplier.setCompanyName(jTextField2.getText());
                currentSupplier.setEmail(jTextField3.getText());
                currentSupplier.setPhone(jTextField4.getText());
                currentSupplier.setAddress(jTextField5.getText());
                boolean success = SuppliersDB.updateSupplier(currentSupplier);
                if (success) {
                    JOptionPane.showMessageDialog(this, "Supplier updated successfully");
                    currentEdit = false;
                    editFields(currentEdit);
                    initialRun();
                } else {
                    JOptionPane.showMessageDialog(this, "Failed to update supplier", "Error", JOptionPane.ERROR_MESSAGE);
                }
            }
        }
    }
