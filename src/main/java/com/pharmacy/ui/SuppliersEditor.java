    private void changeStatus() {
        SuppliersDB.Supplier currentSupplier = suppliers.get(currentIndex);
        if (currentSupplier != null) {
            boolean newStatus = !currentSupplier.isActive();
            boolean success = SuppliersDB.updateSupplierStatus(currentSupplier.getSupplierId(), newStatus);
            if (success) {
                currentSupplier.setActive(newStatus);
                displaySupplier(currentIndex);
                String statusText = newStatus ? "activated" : "deactivated";
                JOptionPane.showMessageDialog(this, "Supplier " + statusText + " successfully");
            } else {
                JOptionPane.showMessageDialog(this, "Failed to update supplier status", "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }
