    private boolean exactMatchFound = false;
    private boolean nameNotFoundFully = false;
    private boolean allowUpdates = true;

    private void setupAutoCompleteForComboBox(JComboBox<String> combo) {
        combo.setEditable(true);
        List<String> originalItems = new ArrayList<>();
        for (int i = 0; i < combo.getItemCount(); i++) {
            originalItems.add(combo.getItemAt(i));
        }

        JTextField editor = (JTextField) combo.getEditor().getEditorComponent();
        JPopupMenu popup = new JPopupMenu();
        popup.setFocusable(false);

        JList<String> list = new JList<>();
        list.setFocusable(false);
        JScrollPane scroll = new JScrollPane(list);
        scroll.setBorder(null);
        popup.add(scroll);
        list.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);

        list.addMouseListener(new MouseAdapter() {
            @Override
            public void mouseClicked(MouseEvent e) {
                if (!list.isSelectionEmpty()) {
                    allowUpdates = false;
                    editor.setText(list.getSelectedValue());
                    popup.setVisible(false);
                    editor.requestFocus();
                    SwingUtilities.invokeLater(() -> allowUpdates = true);
                }
            }
        });

        editor.getDocument().addDocumentListener(new DocumentListener() {

            private void updateSuggestions() {
                if (!allowUpdates) {
                    return;
                }

                SwingUtilities.invokeLater(() -> {
                    String typed = editor.getText().trim().toLowerCase();

                    exactMatchFound = originalItems.stream()
                            .anyMatch(s -> s.equalsIgnoreCase(typed));

                    nameNotFoundFully = !typed.isEmpty() && !exactMatchFound;

                    if (typed.isEmpty()) {
                        popup.setVisible(false);
                        return;
                    }

                    List<String> filtered = originalItems.stream()
                            .filter(s -> s.toLowerCase().contains(typed))
                            .toList();

                    if (filtered.isEmpty()) {
                        popup.setVisible(false);
                        return;
                    }

                    list.setListData(filtered.toArray(new String[0]));
                    list.setSelectedIndex(0);

                    popup.setPopupSize(combo.getWidth(), 120);
                    popup.show(combo, 0, combo.getHeight());
                });
            }

            @Override
            public void insertUpdate(DocumentEvent e) {
                updateSuggestions();
            }

            @Override
            public void removeUpdate(DocumentEvent e) {
                updateSuggestions();
            }

            @Override
            public void changedUpdate(DocumentEvent e) {
                updateSuggestions();
            }
        });
    }


