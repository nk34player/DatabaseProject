    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        String username = jTextField1.getText();
        String password = jPasswordField1.getText();

        int status = UsersDB.login(username, password);
        switch (status) {
            case 2:
                ManagerDashboard dashboard = new ManagerDashboard();
                dashboard.setVisible(true);
                this.setVisible(false);
                break;
            case 3:
                break;
            case 4:
                break;
            case 1:
                JOptionPane.showMessageDialog(null, "The user isn't verified yet, contact an adminstrator", "Login failed!!", JOptionPane.ERROR_MESSAGE);
                break;
            default:
                JOptionPane.showMessageDialog(null, "Login failed!!", "Authentication error", JOptionPane.ERROR_MESSAGE);
                break;
        }
    }//GEN-LAST:event_jButton1ActionPerformed

