    private void deleteCurrentUser() {
        Category curCategory = categories.get(currentIndex);
        if (curCategory != null) {
            int confirm = JOptionPane.showConfirmDialog(this, "Are you sure you want to delete this user?", "Confirm Delete", JOptionPane.YES_NO_OPTION);
            if (confirm == JOptionPane.YES_OPTION) {
                CategoriesDB.deleteCategory(curCategory.getCategoryId());
                editFields(false);
                initialRun();
            }
        }
    }

    private void saveBtn() {
        Category curCategory = categories.get(currentIndex);
        if (curCategory != null) {
            curCategory.setCategoryName(jTextField1.getText());
            curCategory.setDescription(jTextArea1.getText());
            CategoriesDB.updateCategory(curCategory);
            currentEdit = false;
            editFields(currentEdit);
            initialRun();
        }
    }

    private void updateButtons() {
        jButton7.setEnabled(currentIndex > 0);
        jButton6.setEnabled(currentIndex < categories.size() - 1);
    }

    public void previousUser() {
        if (currentIndex > 0) {
            currentIndex--;
            currentEdit = false;
            editFields(currentEdit);
            displayCategory(currentIndex);
        }
        updateButtons();
    }

    public void nextUser() {
        if (currentIndex < categories.size() - 1) {
            currentIndex++;
            currentEdit = false;
            editFields(currentEdit);
            displayCategory(currentIndex);
        }
        updateButtons();
    }

