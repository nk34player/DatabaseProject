    private List<Category> categories;
    private Integer currentIndex;
    private Boolean currentEdit = false;

    private void clearFields() {
        jTextField1.setText("");
        jTextArea1.setText("");
    }

    private void editFields(Boolean edit) {
        if (edit == true) {
            jButton9.setEnabled(true);
            jButton8.setEnabled(false);
            jTextField1.setEditable(true);
            jTextArea1.setEditable(true);
        } else {
            jButton9.setEnabled(false);
            jButton8.setEnabled(true);
            jTextField1.setEditable(false);
            jTextArea1.setEditable(false);
        }
    }

    private void displayCategory(int index) {
        if (index >= 0 && index < categories.size()) {
            Category category = categories.get(index);
            jTextField1.setText(category.getCategoryName());
            jTextArea1.setText(category.getDescription());
        }
    }

    private void loadData() {
        categories = CategoriesDB.getAllCategories();
        if (!categories.isEmpty()) {
            currentIndex = 0;
            displayCategory(currentIndex);
        }
    }

    private void loadIcon() {
        ImageIcon originalIcon = new ImageIcon(getClass().getResource("/left-arrow-white.png"));
        Image scaledImage = originalIcon.getImage().getScaledInstance(32, 32, Image.SCALE_SMOOTH);
        ImageIcon resizedIcon = new ImageIcon(scaledImage);
        jButton7.setIcon(resizedIcon);

        originalIcon = new ImageIcon(getClass().getResource("/right-arrow-white.png"));
        scaledImage = originalIcon.getImage().getScaledInstance(32, 32, Image.SCALE_SMOOTH);
        resizedIcon = new ImageIcon(scaledImage);
        jButton6.setIcon(resizedIcon);

        jButton6.setText("");
        jButton7.setText("");
    }

    private void initialRun() {
        loadIcon();
        clearFields();
        loadData();
        currentEdit = false;
        editFields(currentEdit);
    }

