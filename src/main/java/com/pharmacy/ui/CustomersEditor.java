    private void deleteCurrentCustomer() {
        CustomersDB.Customer currentCustomer = customers.get(currentIndex);
        if (currentCustomer != null) {
            int confirm = JOptionPane.showConfirmDialog(this, "Are you sure you want to delete this customer?", "Confirm Delete", JOptionPane.YES_NO_OPTION);
            if (confirm == JOptionPane.YES_OPTION) {
                CustomersDB.deleteCustomer(currentCustomer.getCustomerId());
                editFields(false);
                initialRun();
            }
        }
    }

    private void saveBtn() {
        CustomersDB.Customer currrentCustomer = customers.get(currentIndex);
        if (currrentCustomer != null) {
            if (validateFields()) {
                currrentCustomer.setFullName(jTextField1.getText());
                currrentCustomer.setPhone(jTextField2.getText());
                currrentCustomer.setEmail(jTextField3.getText());
                currrentCustomer.setCity(jTextField4.getText());
                currrentCustomer.setStreetAddress(jTextField5.getText());
                boolean success = CustomersDB.updateCustomer(currrentCustomer);
                if (success) {
                    JOptionPane.showMessageDialog(this, "Customer updated successfully");
                    currentEdit = false;
                    editFields(currentEdit);
                    initialRun();
                } else {
                    JOptionPane.showMessageDialog(this, "Failed to update customer", "Error", JOptionPane.ERROR_MESSAGE);
                }
            }
        }
    }
    
    private void updateButtons() {
        jButton7.setEnabled(currentIndex > 0);
        jButton6.setEnabled(currentIndex < customers.size() - 1);
    }

    public void previousCustomer() {
        if (currentIndex > 0) {
            currentIndex--;
            updateButtons();
            currentEdit = false;
            editFields(currentEdit);
            displayCustomer(currentIndex);
        }
    }

    public void nextCustomer() {
        if (currentIndex < customers.size() - 1) {
            currentIndex++;
            updateButtons();
            currentEdit = false;
            editFields(currentEdit);
            displayCustomer(currentIndex);
        }
    }

