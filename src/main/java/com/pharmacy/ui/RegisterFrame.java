        String username = jTextField1.getText();
        String password = jPasswordField1.getText();
        String role = (String) jComboBox1.getSelectedItem();
        System.out.println(username + password + role);
        int status = UsersDB.register(username, password, role);
        switch (status) {
            case 1:
                JOptionPane.showMessageDialog(null, "A new account has been made", "Register sucesseded", JOptionPane.ERROR_MESSAGE);
                break;
            case 0:
                JOptionPane.showMessageDialog(null, "User already exists", "Register failed!!", JOptionPane.ERROR_MESSAGE);
                break;
            default:
                JOptionPane.showMessageDialog(null, "Authentication error", "Login failed!!", JOptionPane.ERROR_MESSAGE);
                break;
        }
