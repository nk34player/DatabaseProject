    public void updateOrderedAmount(int ordered) {
        if (ordered > 0){
            stockLbl.setText("Stock quantity: "
                + medicine.getStockQuantity()
                + " - "
                + ordered);
        } else {
            stockLbl.setText("Stock quantity: " + medicine.getStockQuantity());
        }
        
    }

